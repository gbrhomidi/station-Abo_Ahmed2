package com.aistudio.dieselstationsms.kxmpzq.startup.retry

/**

* عقد سياسة إعادة المحاولة المستخدمة بواسطة منظومة Startup.

* 

* المسؤولية:

* 

* 1. تحديد الحد الأقصى لمحاولات تنفيذ المرحلة.

* 2. تحديد ما إذا كان الاستثناء قابلًا لإعادة المحاولة.

* 3. تحديد ما إذا كانت نتيجة الفشل النصية قابلة لإعادة المحاولة.

* 4. حساب مدة الانتظار قبل محاولة التنفيذ التالية.

* 

* ملاحظة مهمة حول attempt:

* ───────────────────────────────────────────────────────────────

* 

* InitializationPipeline يستخدم فهرس المحاولة ابتداءً من الصفر:

* 

* 0 until maxAttempts

* 

* وبالتالي:

* 

* attempt = 0  → المحاولة الأولى

* attempt = 1  → المحاولة الثانية

* attempt = 2  → المحاولة الثالثة

* 

* إذا كانت:

* 

* maxAttempts = 3

* 

* فإن عدد المحاولات الفعلي هو ثلاث محاولات فقط.

* 

* لذلك يجب أن تكون دوال shouldRetry() قادرة على منع إعادة المحاولة

* بعد آخر محاولة.
  */
  interface RetryPolicy {
  
  /**
  
  * العدد الإجمالي الأقصى لمحاولات التنفيذ.
  * 
  * يجب أن تكون القيمة أكبر من صفر.
    */
    val maxAttempts: Int
  
  /**
  
  * مدة التأخير الأساسية بين محاولات التنفيذ، بالميلي ثانية.
  * 
  * القيمة صفر مسموحة إذا كان المطلوب تعطيل التأخير.
    */
    val backoffMs: Long
  
  /**
  
  * تحديد ما إذا كان الاستثناء الناتج عن محاولة معينة
  * يستحق إعادة المحاولة.
  * 
  * @param attempt فهرس المحاولة، يبدأ من 0.
  * @param error الاستثناء الذي تسبب في الفشل.
  * 
  * @return true إذا كان من المسموح إجراء محاولة أخرى.
    */
    fun shouldRetry(
    attempt: Int,
    error: Throwable
    ): Boolean
  
  /**
  
  * تحديد ما إذا كانت نتيجة فشل نصية قابلة لإعادة المحاولة.
  * 
  * هذه الدالة جزء من العقد العام للسياسة، حتى إذا كان
  * المسار الحالي في InitializationPipeline يعتمد أساسًا
  * على PhaseResult.Failure.
  * 
  * @param attempt فهرس المحاولة، يبدأ من 0.
  * @param error رسالة الخطأ.
  * 
  * @return true إذا كان من المسموح إجراء محاولة أخرى.
    */
    fun shouldRetryResult(
    attempt: Int,
    error: String
    ): Boolean
  
  /**
  
  * حساب مدة الانتظار قبل محاولة التنفيذ التالية.
  * 
  * @param attempt فهرس المحاولة التي انتهت بالفشل، يبدأ من 0.
  * 
  * @return مدة الانتظار بالميلي ثانية.
    */
    fun getDelayMs(
    attempt: Int
    ): Long
    }