package com.aistudio.dieselstationsms.kxmpzq.startup

/**
 * ═══════════════════════════════════════════════════════════════
 * أسباب بدء تشغيل منظومة SMS - StartupReason
 * ═══════════════════════════════════════════════════════════════
 *
 * يحدد هذا الـ enum السبب الذي أدى إلى طلب تشغيل SMSService.
 *
 * مهم:
 * - أسماء القيم جزء من عقد التكامل الداخلي.
 * - SmsServiceLauncher يمرر reason.name إلى SMSService.
 * - لذلك يجب عدم إعادة تسمية القيم دون تحديث جميع المستهلكين
 *   لها في منظومة startup وSMSService.
 */
enum class StartupReason {

    /**
     * تشغيل الجهاز بعد الإقلاع.
     *
     * يستخدم عندما تبدأ منظومة التطبيق نتيجة BOOT_COMPLETED
     * أو حدث إقلاع النظام المكافئ الذي يعالجه المشروع.
     */
    BOOT,

    /**
     * تشغيل الخدمة بعد تحديث التطبيق.
     *
     * يستخدم لضمان إعادة تهيئة خدمة SMS بعد تثبيت إصدار جديد
     * من التطبيق.
     */
    APP_UPDATED,

    /**
     * تغير وقت النظام.
     *
     * يستخدم عندما يتغير وقت الجهاز بصورة تؤثر على جدولة
     * أو منطق التوقيت المرتبط بخدمة SMS.
     */
    TIME_CHANGED,

    /**
     * تغير المنطقة الزمنية للجهاز.
     *
     * منفصل عن TIME_CHANGED لأن تغيير المنطقة الزمنية قد يحدث
     * دون أن يكون مجرد تعديل مباشر للساعة.
     */
    TIMEZONE_CHANGED,

    /**
     * تشغيل الخدمة بواسطة Alarm / آلية جدولة النظام.
     */
    ALARM,

    /**
     * تشغيل يدوي مقصود.
     *
     * مثل طلب التشغيل من واجهة التطبيق أو إجراء إداري داخلي.
     */
    MANUAL,

    /**
     * إعادة تشغيل الخدمة بعد اكتشاف تعطل أو فشل سابق.
     *
     * يجب أن يبقى هذا السبب مميزًا عن BOOT وMANUAL حتى تتمكن
     * منظومة Recovery/Metrics من معرفة أن التشغيل ناتج عن تعافٍ.
     */
    CRASH_RECOVERY,

    /**
     * تشغيل ناتج عن جدولة داخلية أو دورة مجدولة.
     *
     * يختلف عن ALARM عندما يكون مصدر الطلب من Scheduler
     * الداخلي لمنظومة التطبيق.
     */
    SCHEDULED,

    /**
     * تشغيل/استئناف الخدمة بعد أن يقوم المستخدم بفتح قفل الجهاز.
     *
     * مهم للأجهزة التي تكون خدماتها أو بياناتها غير متاحة
     * قبل USER_UNLOCKED بعد الإقلاع.
     */
    USER_UNLOCKED
}