package com.aistudio.dieselstationsms.kxmpzq

import java.io.File
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [28])
class InvoicePdfSupportTest {
    @Test fun fileNameSanitizationIsStableAndBlocksPathTraversal() {
        assertEquals("INV_2026_001", InvoicePdfSupport.sanitizeInvoiceFileName("../INV 2026/001"))
        assertEquals("فاتورة_١٢٣", InvoicePdfSupport.sanitizeInvoiceFileName("فاتورة ١٢٣"))
        assertEquals("", InvoicePdfSupport.sanitizeInvoiceFileName(" ../ "))
    }

    @Test fun rejectsMissingAndMalformedPdf() {
        val missing = File.createTempFile("invoice-missing", ".pdf").apply { delete() }
        assertFalse(InvoicePdfSupport.isPdfVisuallyNonBlank(missing))

        val malformed = File.createTempFile("invoice-bad", ".pdf")
        try {
            malformed.writeText("not a PDF")
            assertFalse(InvoicePdfSupport.isPdfVisuallyNonBlank(malformed))
        } finally {
            malformed.delete()
        }
    }

    @Test fun longInvoicePaginationCoversEverySourceRowWithoutGapsOrOverlap() {
        val slices = InvoicePdfSupport.calculatePageSlices(
            sourceWidth = 794,
            sourceHeight = 2500
        )

        assertEquals(3, slices.size)
        assertEquals(0, slices.first().sourceTop)
        assertEquals(2500, slices.last().sourceBottom)
        slices.zipWithNext().forEach { (current, next) ->
            assertEquals(current.sourceBottom, next.sourceTop)
        }
        assertTrue(slices.all { it.sourceTop < it.sourceBottom })
        assertTrue(slices.all { it.targetHeight in 1..842 })
        assertEquals(841, slices[0].targetHeight)
        assertEquals(841, slices[1].targetHeight)
        assertEquals(190, slices[2].targetHeight)
    }

    @Test fun paginationRejectsInvalidBitmapOrPageGeometry() {
        var rejected = false
        try {
            InvoicePdfSupport.calculatePageSlices(0, 100)
        } catch (_: IllegalArgumentException) {
            rejected = true
        }
        assertTrue(rejected)
    }

    // PdfDocument/PdfRenderer require Android's native PDF implementation, which Robolectric's
    // current test runtime does not reliably emulate (PdfDocument reports itself closed even
    // before a page can be started). Keep these JVM tests deterministic; visual rendering and
    // multi-page validation must be covered with an instrumented/device test rather than a
    // synthetic PDF generated by the Robolectric shadow.
}
