const fs = require('fs');
const dbPath = 'app/src/main/java/com/aistudio/dieselstationsms/kxmpzq/DatabaseHelper.kt';
const bridgePath = 'app/src/main/java/com/aistudio/dieselstationsms/kxmpzq/MainActivity.kt';
const salesPath = 'app/src/main/assets/screens/sales-reports.html';
const inventoryPath = 'app/src/main/assets/screens/inventory-reports.html';
const fuelPath = 'app/src/main/assets/screens/fuel-reports.html';
const readingsPath = 'app/src/main/assets/screens/meter-readings.html';
const mainPath = 'app/src/main/assets/main.html';
const db = fs.readFileSync(dbPath, 'utf8');
const bridge = fs.readFileSync(bridgePath, 'utf8');
const sales = fs.readFileSync(salesPath, 'utf8');
const inventory = fs.readFileSync(inventoryPath, 'utf8');
const fuel = fs.readFileSync(fuelPath, 'utf8');
const readings = fs.readFileSync(readingsPath, 'utf8');
const main = fs.readFileSync(mainPath, 'utf8');
const failures = [];
function need(text, pattern, label) { if (!pattern.test(text)) failures.push(label); }
need(db, /fun getDashboardStats\(stationId: Int, params: JSONObject = JSONObject\(\)\)/, 'DatabaseHelper: parameterized dashboard stats missing');
need(db, /getSalesAmountBetween\(stationId, currentStart, currentEnd\)/, 'DatabaseHelper: current-period SQL aggregate missing');
need(db, /getSalesAmountBetween\(stationId, previousStart, previousEnd\)/, 'DatabaseHelper: previous-equivalent-period SQL aggregate missing');
need(db, /sales_trend_data/, 'DatabaseHelper: structured sales trend missing');
need(db, /products_trend_data/, 'DatabaseHelper: structured product trend missing');
need(db, /getOperationalTotalCount/, 'DatabaseHelper: operational COUNT metadata missing');
need(db, /put\("total_count", totalCount\)/, 'DatabaseHelper: total_count missing');
need(db, /put\("total_pages", totalPages\)/, 'DatabaseHelper: total_pages missing');
need(db, /LIMIT \? OFFSET \?/, 'DatabaseHelper: LIMIT/OFFSET missing');
need(db, /CREATE TABLE IF NOT EXISTS meter_readings/, 'DatabaseHelper: meter_readings schema missing');
need(db, /"meter_readings" -> "reading_date"/, 'DatabaseHelper: meter_readings date filter missing');
need(db, /fun getFuelReportPage\(data: JSONObject, stationScopeId: Int\): JSONObject/, 'DatabaseHelper: fuel page method missing');
need(db, /getFuelReportTotalCount/, 'DatabaseHelper: fuel COUNT metadata missing');
need(db, /val requestedSort = data.optString\("sort_by", "date"\)/, 'DatabaseHelper: allow-listed fuel report sort missing');
need(db, /val orderBy = if \(sortColumn == "id"\) "id \$sortDirection, type ASC"/, 'DatabaseHelper: deterministic cross-source fuel ordering missing');
need(bridge, /@JavascriptInterface\s+fun getFuelReportPage\(/, 'MainActivity: getFuelReportPage bridge missing');
need(bridge, /@JavascriptInterface\s+fun getMeterReadingRecords\(/, 'MainActivity: meter-reading list bridge missing');
need(bridge, /@JavascriptInterface\s+fun generateMeterReadingReport\(/, 'MainActivity: meter-reading report bridge missing');
need(sales, /limit: state\.pagination\.pageSize/, 'sales UI: bounded page size missing');
need(sales, /offset: \(state\.pagination\.page - 1\) \* state\.pagination\.pageSize/, 'sales UI: page offset missing');
need(sales, /total_count/, 'sales UI: total_count consumption missing');
need(sales, /function renderPagination\(/, 'sales UI: pagination controls missing');
need(inventory, /apiCall\('generateInventoryReport'/, 'inventory UI: production report bridge missing');
need(inventory, /total_count/, 'inventory UI: total_count contract missing');
need(fuel, /getFuelReportPage/, 'fuel UI: paged fuel bridge missing');
need(fuel, /search: search/, 'fuel UI: server-side search missing');
need(fuel, /function goToPage\(page\)[\s\S]{0,220}generateReport\(targetPage\)/, 'fuel UI: server-side pagination navigation missing');
need(fuel, /total_pages/, 'fuel UI: page metadata consumption missing');
need(fuel, /sort_by: fuelSort\.by/, 'fuel UI: sort state is not sent to SQLite');
need(fuel, /sort_dir: fuelSort\.direction/, 'fuel UI: sort direction is not sent to SQLite');
need(fuel, /function applyPreset\(presetId\)/, 'fuel UI: quick preset handler missing');
need(fuel, /pagination\.page = 1;\s*generateReport\(\);\s*haptic\('light'\)/, 'fuel UI: quick presets do not reload the filtered SQLite result');
if (/filterByPreset\(state\.allRows, state\.activePreset\)/.test(fuel)) failures.push('fuel UI: quick presets still filter/sort only the current page');
need(readings, /"reportKind": "operational:MeterReading"/, 'meter readings UI: report bridge configuration missing');
need(readings, /"listMethod": "getMeterReadingRecords"/, 'meter readings UI: SQLite list bridge missing');
need(readings, /invoke\('generate' \+ suffix \+ 'Report'/, 'meter readings UI: operational report bridge missing');
need(readings, /limit: REPORT_PAGE_SIZE/, 'meter readings UI: bounded page-size contract missing');
need(readings, /offset: \(reportPage - 1\) \* REPORT_PAGE_SIZE/, 'meter readings UI: report offset contract missing');
need(readings, /renderReportPagination/, 'meter readings UI: pagination controls missing');
need(db, /appendMeterReadingFilters\(params, where, args\)/, 'meter readings: shared row/COUNT filter builder missing');
need(db, /pump_id = \?/, 'meter readings: pump filter missing');
need(db, /LOWER\(COALESCE\(period, ''\)\) = LOWER\(\?\)/, 'meter readings: period filter missing');
need(db, /COALESCE\(is_balanced, 0\) = 1/, 'meter readings: balanced filter missing');
need(db, /COALESCE\(is_balanced, 0\) = 0/, 'meter readings: unbalanced filter missing');
need(main, /sales_trend_data/, 'main UI: structured sales trend consumer missing');
need(main, /products_trend_data/, 'main UI: structured product trend consumer missing');
console.log('Backend capability contract checked: Trends, Pagination, Fuel Readings.');
if (failures.length) { console.error(failures.join('\n')); process.exit(1); }
console.log('Backend capability contract PASS.');
