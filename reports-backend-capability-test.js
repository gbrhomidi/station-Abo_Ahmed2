const fs = require('fs');
const dbPath = 'app/src/main/java/com/aistudio/dieselstationsms/kxmpzq/DatabaseHelper.kt';
const bridgePath = 'app/src/main/java/com/aistudio/dieselstationsms/kxmpzq/MainActivity.kt';
const salesPath = 'app/src/main/assets/screens/sales-reports.html';
const fuelPath = 'app/src/main/assets/screens/fuel-reports.html';
const mainPath = 'app/src/main/assets/main.html';
const db = fs.readFileSync(dbPath, 'utf8');
const bridge = fs.readFileSync(bridgePath, 'utf8');
const sales = fs.readFileSync(salesPath, 'utf8');
const fuel = fs.readFileSync(fuelPath, 'utf8');
const main = fs.readFileSync(mainPath, 'utf8');
const failures = [];
function need(text, pattern, label) { if (!pattern.test(text)) failures.push(label); }
need(db, /fun getDashboardStats\(stationId: Int = 1, params: JSONObject = JSONObject\(\)\)/, 'DatabaseHelper: parameterized dashboard stats missing');
need(db, /getSalesAmountBetween\(stationId, currentStart, currentEnd\)/, 'DatabaseHelper: current-period SQL aggregate missing');
need(db, /getSalesAmountBetween\(stationId, previousStart, previousEnd\)/, 'DatabaseHelper: previous-equivalent-period SQL aggregate missing');
need(db, /sales_trend_data/, 'DatabaseHelper: structured sales trend missing');
need(db, /products_trend_data/, 'DatabaseHelper: structured product trend missing');
need(db, /getOperationalTotalCount/, 'DatabaseHelper: operational COUNT metadata missing');
need(db, /put\("total_count", totalCount\)/, 'DatabaseHelper: total_count missing');
need(db, /put\("total_pages", totalPages\)/, 'DatabaseHelper: total_pages missing');
need(db, /LIMIT \? OFFSET \?/, 'DatabaseHelper: LIMIT/OFFSET missing');
need(db, /CREATE TABLE IF NOT EXISTS meter_readings/, 'DatabaseHelper: meter_readings schema missing');
need(db, /"meter_readings" -> "reading_date"/, 'DatabaseHelper: meter_readings date filter missing');
need(db, /fun getFuelReportPage\(data: JSONObject\): JSONObject/, 'DatabaseHelper: fuel page method missing');
need(db, /getFuelReportTotalCount/, 'DatabaseHelper: fuel COUNT metadata missing');
need(bridge, /@JavascriptInterface\s+fun getFuelReportPage\(/, 'MainActivity: getFuelReportPage bridge missing');
need(bridge, /@JavascriptInterface\s+fun getMeterReadingRecords\(/, 'MainActivity: meter-reading list bridge missing');
need(bridge, /@JavascriptInterface\s+fun generateMeterReadingReport\(/, 'MainActivity: meter-reading report bridge missing');
need(sales, /limit: salesPagination\.pageSize/, 'sales UI: pageSize request missing');
need(sales, /offset: \(salesPagination\.page - 1\) \* salesPagination\.pageSize/, 'sales UI: offset request missing');
need(sales, /total_count/, 'sales UI: total_count consumption missing');
need(sales, /goToSalesPage/, 'sales UI: navigation controls missing');
need(fuel, /generateMeterReadingReport/, 'fuel UI: real readings bridge missing');
need(fuel, /getFuelReportPage/, 'fuel UI: paged fuel bridge missing');
need(fuel, /meter_readings|reading_code/, 'fuel UI: meter-reading fields missing');
need(fuel, /goToFuelPage/, 'fuel UI: fuel pagination controls missing');
need(main, /sales_trend_data/, 'main UI: structured sales trend consumer missing');
need(main, /products_trend_data/, 'main UI: structured product trend consumer missing');
console.log('Backend capability contract checked: Trends, Pagination, Fuel Readings.');
if (failures.length) { console.error(failures.join('\n')); process.exit(1); }
console.log('Backend capability contract PASS.');
