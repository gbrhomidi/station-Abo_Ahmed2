const fs = require('fs');
const assert = require('assert');
const { JSDOM } = require('jsdom');
const path = require('path');

const html = fs.readFileSync(path.join(__dirname, 'app/src/main/assets/screens/drivers.html'), 'utf8').replace(/<script\s+src=[\s\S]*?<\/script>/gi, '');
const calls = [];
let currentRows = [{
  id: 11, driver_code: 'DRV-11', full_name: 'Ahmed Driver', full_name_ar: 'أحمد السائق', nationality: 'Saudi',
  phone: '0500000000', phone2: '0511111111', email: 'ahmed@example.com', license_number: 'LIC-11',
  license_type: 'Heavy', license_issue_date: '2025-01-01', license_expiry_date: '2027-01-01',
  vehicle_id: 22, status: 'active', hire_date: '2025-04-01', salary: 4500, extra_data: JSON.stringify({ availability: 'available' }), is_deleted: 0
}];
const vehicles = [{ id: 22, vehicle_id: 22, vehicle_code: 'VEH-22', plate_number: 'ABC-22', brand: 'Toyota', model: 'Hilux', status: 'active' }];
const trips = [{ id: 301, vehicle_id: 22, driver_id: 11, trip_date: '2026-08-20', start_location: 'المحطة', end_location: 'العميل', distance_km: 42 }];
const json = data => JSON.stringify({ success: true, data });

function installBridge(window) {
  window.AndroidInterface = {
    getDriverRecords: payload => { calls.push(['getDriverRecords', JSON.parse(payload)]); return json(currentRows); },
    getVehicleRecords: payload => { calls.push(['getVehicleRecords', JSON.parse(payload)]); return json(vehicles); },
    getVehicleTripRecords: payload => { calls.push(['getVehicleTripRecords', JSON.parse(payload)]); return json(trips); },
    saveDriverRecord: payload => { calls.push(['saveDriverRecord', JSON.parse(payload)]); return JSON.stringify({ success: true, data: 12 }); },
    updateDriverRecord: (id, payload) => { calls.push(['updateDriverRecord', id, JSON.parse(payload)]); return json(true); },
    deleteDriverRecord: id => { calls.push(['deleteDriverRecord', id]); return json(true); },
    restoreDriverRecord: id => { calls.push(['restoreDriverRecord', id]); return json(true); },
    generateDriverReport: payload => { calls.push(['generateDriverReport', JSON.parse(payload)]); return json(currentRows); },
    sendSmsMessageTyped: payload => { calls.push(['sendSmsMessageTyped', JSON.parse(payload)]); return json(33); }
  };
}

(async () => {
  const dom = new JSDOM(html, { runScripts: 'dangerously', url: 'https://drivers.test/', beforeParse(window) {
    installBridge(window);
    window.confirm = () => true;
    window.prompt = message => String(message).includes('الحالة') ? 'inactive' : 'رسالة اختبار';
    window.alert = () => {};
    window.open = () => ({ document: { write() {}, close() {} } });
    window.requestAnimationFrame = callback => { callback(); return 1; };
    window.matchMedia = () => ({ matches: false, addListener() {}, removeListener() {} });
    window.CSS = { escape: value => String(value).replace(/[^a-zA-Z0-9_-]/g, '\\$&') };
    window.URL.createObjectURL = () => 'blob:test';
    window.URL.revokeObjectURL = () => {};
  }});
  const { window } = dom;
  await new Promise(resolve => setTimeout(resolve, 20));
  await window.loadDrivers();

  assert.ok(calls.some(c => c[0] === 'getDriverRecords'), 'driver list must come from getDriverRecords');
  assert.ok(calls.some(c => c[0] === 'getVehicleRecords'), 'vehicle list must come from getVehicleRecords');
  assert.strictEqual(window.document.querySelectorAll('.driver-card').length, 1, 'driver card should render');
  assert.ok(window.document.querySelector('.driver-card').textContent.includes('أحمد السائق'), 'Arabic driver name should render');
  assert.ok(window.document.querySelector('.driver-card').textContent.includes('ABC-22'), 'linked vehicle plate should render');

  window.openForm();
  window.document.getElementById('full_name').value = 'سائق جديد';
  window.document.getElementById('full_name_ar').value = 'سائق جديد عربي';
  window.document.getElementById('phone').value = '0522222222';
  window.document.getElementById('license_issue_date').value = '2026-01-01';
  window.document.getElementById('license_expiry_date').value = '2028-01-01';
  await window.saveForm({ preventDefault() {} });
  const add = calls.find(c => c[0] === 'saveDriverRecord');
  assert.ok(add, 'saveDriverRecord must be called');
  assert.strictEqual(add[1].full_name, 'سائق جديد');
  assert.strictEqual(add[1].driver_code, undefined, 'driver code must be generated by SQLite layer');

  window.openForm(currentRows[0]);
  window.document.getElementById('status').value = 'suspended';
  window.document.getElementById('vehicle_id').value = '22';
  assert.strictEqual(window.document.getElementById('vehicle_id').options.length, 2, 'real vehicle option should load in driver form');
  await window.saveForm({ preventDefault() {} });
  const update = calls.filter(c => c[0] === 'updateDriverRecord').at(-1);
  assert.ok(update, 'updateDriverRecord must be called');
  assert.strictEqual(update[1], 11);
  assert.strictEqual(update[2].status, 'suspended');
  assert.strictEqual(update[2].vehicle_id, 22, 'driver vehicle_id must be numeric');

  await window.archiveOrRestore(currentRows[0]);
  assert.ok(calls.some(c => c[0] === 'deleteDriverRecord' && c[1] === 11), 'archive must use soft-delete driver contract');
  await window.archiveOrRestore({ ...currentRows[0], is_deleted: 1 });
  assert.ok(calls.some(c => c[0] === 'restoreDriverRecord' && c[1] === 11), 'restore must use restoreDriverRecord');

  window.openDetails(11);
  await new Promise(resolve => setTimeout(resolve, 10));
  assert.ok(calls.some(c => c[0] === 'getVehicleTripRecords'), 'driver details should load linked trips from SQLite');
  window.document.querySelector('[data-tab="trips"]').click();
  assert.ok(window.document.getElementById('detailsContent').textContent.includes('المحطة'), 'linked trip should render');

  const select = window.document.querySelector('.driver-select');
  assert.ok(select, 'selection checkbox must render');
  select.click();
  await window.bulkStatus();
  assert.ok(calls.some(c => c[0] === 'updateDriverRecord' && c[2].status === 'inactive'), 'bulk status must update selected driver');
  const nextSelect = window.document.querySelector('.driver-select');
  nextSelect.click();
  await window.bulkArchive();
  assert.ok(calls.filter(c => c[0] === 'deleteDriverRecord' && c[1] === 11).length >= 2, 'bulk archive must call deleteDriverRecord for selected driver');
  const smsSelect = window.document.querySelector('.driver-select');
  smsSelect.click();
  await window.bulkSms();
  assert.ok(calls.some(c => c[0] === 'sendSmsMessageTyped'), 'bulk SMS must use existing SMS bridge');

  window.openReport();
  await window.generateReport();
  assert.ok(calls.some(c => c[0] === 'generateDriverReport'), 'driver report must use generateDriverReport');
  assert.ok(window.document.getElementById('reportOutput').textContent.includes('DRV-11'), 'report output should render real bridge rows');

  console.log('drivers Android Bridge unit tests: PASS (12 assertion groups)');
  dom.window.close();
})().catch(error => { console.error(error.stack || error); process.exitCode = 1; });
